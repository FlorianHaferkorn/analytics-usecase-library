#!/usr/bin/env python3
"""
generate_semantic_model.py
==========================
Generates a complete Power BI PBIP Semantic Model folder (TMDL format)
from a Blueprint YAML + Data Contract YAML.

TMDL specification: https://learn.microsoft.com/analysis-services/tmdl/tmdl-overview
Folder structure per domain:
  dist/<Domain>.SemanticModel/
    definition.pbism
    definition/
      model.tmdl          <- model header + ref table declarations
      expressions.tmdl    <- GoldDataPath parameter
      tables/
        <table>.tmdl      <- one file per table (from data contract)
        _Measures.tmdl    <- PRESERVED if exists (generated by generate_tmdl_measures)
      relationships/
        <name>.tmdl       <- one file per relationship (from blueprint)
      roles/
        <name>.tmdl       <- one file per RLS role (from blueprint)

Usage:
  python generate_semantic_model.py --domain Finance
  python generate_semantic_model.py --all
  python generate_semantic_model.py --domain Finance --gold-path /data/gold

Author: Generated from TMDL spec (Microsoft Learn) + Aurora Blueprint
"""

